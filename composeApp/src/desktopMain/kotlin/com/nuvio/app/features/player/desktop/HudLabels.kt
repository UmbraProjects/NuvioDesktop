/** The keys the map covers; HudLabelsTest checks the HUD references nothing else. */
internal val hudLabelKeys: Set<String> get() = hudLabelResources.keys

@Volatile
private var cachedHudLabels: Pair<String, String>? = null

// Compose substitutes %1$s-style placeholders even when no arguments are given (and throws), so
// templated HUD strings are resolved with each placeholder passed back as its own argument: the HUD
// gets the template and fills it in through hudFormat.
private val placeholderPassThrough: Array<Any> = Array(9) { "%${it + 1}\$s" }

/** The resolved labels as a JSON object, cached per app locale. */
internal fun hudLabelsJson(): String {
    val locale = Locale.getDefault().toLanguageTag()
    cachedHudLabels?.takeIf { it.first == locale }?.let { return it.second }
    val json = JsonObject(hudLabelResources.mapValues { (_, resource) -> JsonPrimitive(localizedString(resource, *placeholderPassThrough)) }).toString()
    cachedHudLabels = locale to json
    return json
}

/** Prepends `"hudLabels":{...}` to a controls payload object. */
internal fun String.withHudLabels(): String {
    if (!startsWith("{")) return this
    val rest = substring(1)
    val separator = if (rest.trimStart().startsWith("}")) "" else ","
    return "{\"hudLabels\":" + hudLabelsJson() + separator + rest
}
