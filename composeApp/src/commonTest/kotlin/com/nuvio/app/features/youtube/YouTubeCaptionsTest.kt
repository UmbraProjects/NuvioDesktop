package com.nuvio.app.features.youtube

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

class YouTubeCaptionsTest {

    private val player = """
        {"responseContext":{"visitorData":"CgtWSVNJVE9S"},
         "captions":{"playerCaptionsTracklistRenderer":{"captionTracks":[
           {"baseUrl":"https://www.youtube.com/api/timedtext?v=vid&lang=en&kind=asr&fmt=srv3","name":{"runs":[{"text":"English (auto-generated)"}]},
            "vssId":"a.en","languageCode":"en","kind":"asr"},
           {"baseUrl":"https://www.youtube.com/api/timedtext?v=vid&lang=de","name":{"simpleText":"German"},"vssId":".de","languageCode":"de"}
         ]}}}
    """.trimIndent()

    @Test
    fun readsTheTracksUploadedOnesFirst() {
        val tracks = parseYouTubeCaptionTracks(player)
        assertEquals(listOf("German", "English (auto-generated)"), tracks.map { it.label })
        assertEquals(listOf(false, true), tracks.map { it.autoGenerated })
        assertEquals("CgtWSVNJVE9S", youTubeVisitorData(player))
        assertEquals(emptyList(), parseYouTubeCaptionTracks("""{"captions":{}}"""))
    }

    @Test
    fun rollingAutoCaptionsBecomeOneLineAtATime() {
        // As YouTube serves an auto-generated track: each cue repeats the previous line, words carry
        // timing tags, and 10 ms cues hold the finished line between them.
        val rolling = """
            WEBVTT
            Kind: captions
            Language: en

            00:00:00.000 --> 00:00:02.500 align:start position:0%

            hello<00:00:00.320><c> there</c><00:00:00.800><c> everyone</c>

            00:00:02.500 --> 00:00:02.510 align:start position:0%
            hello there everyone


            00:00:02.510 --> 00:00:05.000 align:start position:0%
            hello there everyone
            welcome<00:00:02.900><c> back</c>

            00:00:05.000 --> 00:00:05.010 align:start position:0%
            welcome back

        """.trimIndent()

        assertEquals(
            "WEBVTT\n\n" +
                "00:00:00.000 --> 00:00:02.500\nhello there everyone\n\n" +
                "00:00:02.510 --> 00:00:05.000\nwelcome back\n\n",
            plainYouTubeCaptions(rolling),
        )
    }

    @Test
    fun anUploadedTrackIsLeftAsItIs() {
        val uploaded = "WEBVTT\n\n00:00:01.000 --> 00:00:03.000\nA line someone wrote\n"
        assertEquals(uploaded, plainYouTubeCaptions(uploaded))
    }

    @Test
    fun theUrlAsksForWebVttAndCarriesAToken() {
        val base = "https://www.youtube.com/api/timedtext?v=vid&lang=en&kind=asr&fmt=srv3"
        assertEquals("https://www.youtube.com/api/timedtext?v=vid&lang=en&kind=asr&fmt=vtt", youTubeCaptionUrl(base, null))
        val withToken = youTubeCaptionUrl(base, "Mn+a/b=")
        assertTrue(withToken.endsWith("&fmt=vtt&pot=Mn%2Ba%2Fb%3D&potc=1"), withToken)
        assertEquals(1, Regex("[?&]fmt=").findAll(withToken).count())
    }
}
